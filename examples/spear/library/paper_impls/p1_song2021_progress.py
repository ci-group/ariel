"""P1 — Song et al. 2021, *Autonomous Drone Racing with Deep Reinforcement Learning* (IROS 2021).

Ports the paper's **progress-projection reward**: instead of the telescoping
`d_old − d_new` distance-to-next-gate term (which has ~zero gradient at the
target — DRONE_RESEARCH_RECOMMENDATIONS.md finding G4), reward the drone for
the *component of its velocity along the current path segment* and penalise
lateral deviation from that segment. This turns the return surface into a
proper bowl and gives non-vanishing gradient everywhere along the track.

Concretely, for the current segment (prev_gate → target_gate) with unit
tangent `t`:

    progress   = k_p · <v, t> · dt              (integrated along-track speed)
    lateral    = ||(p − prev_gate) − <p − prev_gate, t> · t||
    r_step     = progress − k_lat · lateral²    (+ existing rate / upright / floor shaping)

The gate-passing +bonus and terminal −10 penalties stay unchanged so the
new reward is a **drop-in replacement** for the telescoping term only; every
other shaping switch on `TorchDroneGateEnv` continues to work.

Paired training entry mirrors `42b_train_blueprint_traj.py`:

    uv run examples/spear/library/paper_impls/p1_song2021_progress.py --smoke
    uv run examples/spear/library/paper_impls/p1_song2021_progress.py --steps 2_000_000

Uses the trajectory drawn/generated by `42a_draw_trajectory.py`.
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np
import torch
from stable_baselines3 import PPO
from stable_baselines3.common.vec_env import VecNormalize

from common import dump_config, dump_results, load_42a, load_42b, new_out_dir


class ProgressRewardEnv(load_42b().BlueprintTrajEnv):
    """`BlueprintTrajEnv` with Song-2021 progress-projection reward.

    Set `reward_mode="progress"` for the paper's reward, `"telescoping"` for
    the parent's original behaviour. In `"progress"` mode the reward per
    step is  `k_p · v·tangent · dt − k_lat · lateral²`, replacing the
    `d_old − d_new` term but keeping all other shaping (rate, upright,
    velocity-toward-gate, altitude floor, gate bonus, terminal −10).
    """

    def __init__(self, *args, reward_mode: str = "progress",
                 k_progress: float = 1.0, k_lateral: float = 0.1, **kwargs):
        if reward_mode not in ("telescoping", "progress"):
            raise ValueError(f"reward_mode={reward_mode!r}")
        super().__init__(*args, **kwargs)
        self.reward_mode = reward_mode
        self.k_progress = float(k_progress)
        self.k_lateral = float(k_lateral)

        # Precompute prev_gate per waypoint index: for gate i, its segment
        # starts at gate (i-1) (or start_pos when i=0 on an open track). For
        # closed tracks the ring wraps naturally; for open tracks the first
        # segment origin is `start_pos`.
        G = self.num_gates
        prev = torch.empty_like(self.gate_pos_t)
        prev[1:] = self.gate_pos_t[:-1]
        prev[0] = self.start_pos_t                 # (3,) → broadcast to (3,)
        self.prev_gate_pos_t = prev

    def step_wait(self):
        if self.reward_mode == "telescoping":
            return super().step_wait()

        # Snapshot pre-step distance to the current target (for continuity
        # of the terminal-penalty logic in the parent) and let the parent
        # compute everything normally, then subtract the telescoping term
        # and add the progress term. Doing it as a post-hoc adjustment
        # keeps the gate-passing / OOB / tilt / collision paths intact.
        pos_old_t = self.world_states[:, 0:3].clone()
        tg_old = (self.target_gates % self.num_gates).clone()
        gpos_old = self.gate_pos_t[tg_old]
        d_old = (pos_old_t - gpos_old).norm(dim=1)

        obs_np, rewards_np, dones_np, infos = super().step_wait()

        # After super().step_wait the parent may have reset done envs, so we
        # need pos_new from the pre-reset state. Recover it: for done envs,
        # the terminal-penalty (-10 / -collision) already dominates so we
        # simply leave those rewards alone. For non-done envs the current
        # `world_states` position is the true post-step position.
        pos_new_t = self.world_states[:, 0:3]
        vel_new_t = self.world_states[:, 3:6]
        gpos_new = self.gate_pos_t[tg_old]
        prev_gpos = self.prev_gate_pos_t[tg_old]

        seg = gpos_new - prev_gpos                                  # (E, 3)
        seg_len = seg.norm(dim=1).clamp(min=1e-6)                  # (E,)
        tangent = seg / seg_len.unsqueeze(1)                       # (E, 3) unit
        along = (vel_new_t * tangent).sum(dim=1)                   # (E,)
        rel = pos_new_t - prev_gpos                                # (E, 3)
        along_pos = (rel * tangent).sum(dim=1, keepdim=True)       # (E, 1)
        closest = prev_gpos + along_pos * tangent                  # (E, 3)
        lateral = (pos_new_t - closest).norm(dim=1)                # (E,)

        d_new = (pos_new_t - gpos_new).norm(dim=1)
        telescoping = (d_old - d_new)                              # (E,)
        progress = self.k_progress * along * self.dt               # (E,)
        lateral_pen = self.k_lateral * lateral.pow(2)              # (E,)

        adj_t = -telescoping + progress - lateral_pen              # (E,)
        adj_np = adj_t.detach().cpu().numpy()

        done_mask = np.asarray(dones_np, dtype=bool)
        rewards_np = rewards_np.astype(np.float32)
        rewards_np[~done_mask] = rewards_np[~done_mask] + adj_np[~done_mask]

        # Log the shaping decomposition on the very first step of each
        # episode for the eval script (rare enough to be cheap).
        for i, info in enumerate(infos):
            info["lateral_dev"] = float(lateral[i].item())
            info["along_speed"] = float(along[i].item())
        return obs_np, rewards_np, done_mask, infos


