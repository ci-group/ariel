def make_env(track: dict, num_envs: int, seed: int, device: str,
             gates_ahead: int, max_steps: int, random_init: bool,
             reward_mode: str, k_progress: float, k_lateral: float):
    t42b = load_42b()
    _bp, props = t42b.build_blueprint_and_propellers()
    g = track["gates_pos"]
    margin = 3.0
    return ProgressRewardEnv(
        num_envs=num_envs,
        propellers=props,
        gates_pos=g,
        gate_yaw=track["gate_yaw"],
        start_pos=track["start_pos"],
        x_bounds=(float(g[:, 0].min() - margin), float(g[:, 0].max() + margin)),
        y_bounds=(float(g[:, 1].min() - margin), float(g[:, 1].max() + margin)),
        z_bounds=(-4.0, 0.5),
        gates_ahead=gates_ahead,
        initialize_at_random_gates=random_init,
        seed=seed,
        device=device,
        max_steps=max_steps,
        upright_bonus=t42b.UPRIGHT_BONUS,
        extra_yaw_rate_pen=t42b.EXTRA_YAW_RATE_PEN,
        velocity_reward_coef=t42b.VELOCITY_REWARD_COEF,
        altitude_floor_z=t42b.ALTITUDE_FLOOR_Z,
        altitude_floor_coef=t42b.ALTITUDE_FLOOR_COEF,
        reward_mode=reward_mode,
        k_progress=k_progress,
        k_lateral=k_lateral,
    )


def evaluate(model, vecnorm, env, max_steps: int) -> dict:
    """Deterministic single-episode rollout from fixed start.

    Reports waypoints completed, mean lateral deviation, total reward. `env`
    must be a `VecNormalize` wrapping a single-env `ProgressRewardEnv` with
    `random_init=False`.
    """
    obs = env.reset()
    total_r = 0.0
    lat_devs = []
    steps = 0
    raw = env.venv  # unwrap VecNormalize
    for _ in range(max_steps):
        action, _ = model.predict(obs, deterministic=True)
        env.step_async(action)
        obs, r, dones, infos = env.step_wait()
        total_r += float(r[0])
        steps += 1
        if "lateral_dev" in infos[0]:
            lat_devs.append(infos[0]["lateral_dev"])
        if bool(dones[0]):
            gates = int(infos[0]["num_gates_passed"][0])
            break
    else:
        gates = int(raw.num_gates_passed[0])
    return {
        "gates_passed": gates,
        "num_gates": raw.num_gates,
        "completion": gates / max(raw.num_gates, 1),
        "steps": steps,
        "reward": total_r,
        "mean_lateral_dev": float(np.mean(lat_devs)) if lat_devs else float("nan"),
        "max_lateral_dev": float(np.max(lat_devs)) if lat_devs else float("nan"),
    }


def train_one(reward_mode: str, args, track: dict, out_dir: Path,
              seed: int) -> dict:
    print(f"\n=== [P1] training reward_mode={reward_mode!r} seed={seed} ===")
    raw = make_env(track, num_envs=args.num_envs, seed=seed,
                   device=args.device, gates_ahead=args.gates_ahead,
                   max_steps=args.max_steps, random_init=True,
                   reward_mode=reward_mode, k_progress=args.k_progress,
                   k_lateral=args.k_lateral)
    env = VecNormalize(raw, norm_obs=True, norm_reward=True,
                       clip_obs=10.0, clip_reward=10.0, gamma=0.99)
    model = PPO(
        "MlpPolicy", env,
        policy_kwargs=dict(net_arch=[256, 256]),
        n_steps=args.n_steps,
        batch_size=max((args.n_steps * args.num_envs) // 8, 64),
        n_epochs=10, gamma=0.99, gae_lambda=0.95,
        learning_rate=3e-4, clip_range=0.2, ent_coef=0.0,
        max_grad_norm=0.5, seed=seed, device=args.device, verbose=0,
    )
    t0 = time.time()
    model.learn(total_timesteps=args.steps)
    train_s = time.time() - t0

    # Fresh single-env for deterministic eval (always uses progress-mode
    # observations for lateral_dev logging, regardless of trained reward).
    eval_raw = make_env(track, num_envs=1, seed=seed + 10_000,
                        device=args.device, gates_ahead=args.gates_ahead,
                        max_steps=args.max_steps, random_init=False,
                        reward_mode="progress",
                        k_progress=args.k_progress, k_lateral=args.k_lateral)
    eval_env = VecNormalize(eval_raw, training=False,
                            norm_obs=env.norm_obs, norm_reward=False,
                            clip_obs=env.clip_obs)
    eval_env.obs_rms = env.obs_rms
    stats = evaluate(model, env, eval_env, args.max_steps)
    stats["train_seconds"] = train_s
    stats["seed"] = seed
    stats["reward_mode"] = reward_mode
    model.save(str(out_dir / f"policy_{reward_mode}_seed{seed}.zip"))
    print(f"[eval {reward_mode}] gates={stats['gates_passed']}/{stats['num_gates']} "
          f"({100*stats['completion']:.0f}%)  reward={stats['reward']:+.1f}  "
          f"lat_dev mean={stats['mean_lateral_dev']:.3f} m")
    return stats


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--trajectory", type=Path,
                   default=Path("__data__/blueprint_traj/trajectory.npz"))
    p.add_argument("--steps", type=int, default=2_000_000)
    p.add_argument("--num-envs", type=int, default=16)
    p.add_argument("--n-steps", type=int, default=1024)
    p.add_argument("--gates-ahead", type=int, default=2)
    p.add_argument("--max-steps", type=int, default=1500)
    p.add_argument("--k-progress", type=float, default=1.0)
    p.add_argument("--k-lateral", type=float, default=0.1)
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    p.add_argument("--device", default="cpu")
    p.add_argument("--modes", nargs="+", default=["telescoping", "progress"],
                   choices=["telescoping", "progress"])
    p.add_argument("--smoke", action="store_true",
                   help="short 40k-step, 1-seed sanity budget")
    args = p.parse_args()

    if args.smoke:
        args.steps = 40_000
        args.num_envs = 4
        args.n_steps = 256
        args.max_steps = 400
        args.seeds = [0]

    if not args.trajectory.exists():
        # Auto-generate a demo figure-8 if the user hasn't drawn one.
        print(f"[P1] no trajectory at {args.trajectory}; generating "
              "demo figure-8 headlessly")
        t42a = load_42a()
        raw_xy, closed = t42a.demo_shape("figure8")
        wp, yaw = t42a.resample_track(raw_xy, 0.8, closed, 7)
        gpos, gyaw, spos = t42a.build_track_arrays(wp, yaw, 1.5)
        args.trajectory.parent.mkdir(parents=True, exist_ok=True)
        t42a.save_track(args.trajectory, raw_xy, gpos, gyaw, spos,
                        1.5, 0.8, closed)

    track = load_42b().load_track(args.trajectory)
    out_dir = new_out_dir("p1_song2021_progress")
    dump_config(out_dir, vars(args))
    print(f"[P1] out_dir: {out_dir}")

    all_results: dict[str, list[dict]] = {m: [] for m in args.modes}
    for seed in args.seeds:
        for mode in args.modes:
            all_results[mode].append(train_one(mode, args, track, out_dir, seed))

    # Aggregate: mean ± std per mode.
    def _agg(rows: list[dict]) -> dict:
        return {
            "completion_mean": float(np.mean([r["completion"] for r in rows])),
            "completion_std":  float(np.std([r["completion"] for r in rows])),
            "reward_mean":     float(np.mean([r["reward"] for r in rows])),
            "lat_dev_mean":    float(np.mean([r["mean_lateral_dev"] for r in rows])),
            "lat_dev_std":     float(np.std([r["mean_lateral_dev"] for r in rows])),
            "n_seeds": len(rows),
        }
    summary = {m: _agg(rows) for m, rows in all_results.items()}
    dump_results(out_dir, {"per_seed": all_results, "summary": summary})

    print("\n=== [P1] paired summary ===")
    for m in args.modes:
        s = summary[m]
        print(f"  {m:>12}: completion={s['completion_mean']:.2f}±{s['completion_std']:.2f}"
              f"  reward={s['reward_mean']:+7.1f}"
              f"  lat_dev={s['lat_dev_mean']:.3f}±{s['lat_dev_std']:.3f} m")
    if set(args.modes) == {"telescoping", "progress"}:
        pt, tt = summary["progress"], summary["telescoping"]
        dcomp = pt["completion_mean"] - tt["completion_mean"]
        dlat = (tt["lat_dev_mean"] - pt["lat_dev_mean"]) / max(tt["lat_dev_mean"], 1e-6)
        print(f"\n[GATE] Δcompletion={dcomp:+.2f}  lat_dev reduction={100*dlat:+.0f}%  "
              f"(target: Δcompletion ≥ 0 AND lat_dev_reduction ≥ 30%)")
    print(f"\n[P1] saved -> {out_dir}")


if __name__ == "__main__":
    main()
